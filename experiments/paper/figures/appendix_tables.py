def tex(value):
    return ''.join({'\\': r'\textbackslash{}', '_': r'\_', '%': r'\%',
                    '&': r'\&', '#': r'\#', '{': r'\{', '}': r'\}',
                    '$': r'\$', '^': r'\textasciicircum{}',
                    '~': r'\textasciitilde{}'}.get(c, c) for c in str(value))


def table(caption, label, columns, header, rows, note='', size='8.5', leading='10'):
    return (r'\begin{table}[!htbp]' + '\n' + r'\centering' + '\n'
            + '\\caption{' + caption + '}\n\\label{' + label + '}\n'
            + f'\\fontsize{{{size}}}{{{leading}}}\\selectfont\n'
            + r'\setlength{\tabcolsep}{3pt}' + '\n'
            + r'\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}' + columns + '@{}}\n'
            + '\\toprule\n' + header + r' \\' + '\n\\midrule\n'
            + '\n'.join(row if row.startswith('\\midrule') else row + r' \\' for row in rows)
            + '\n\\bottomrule\n\\end{tabular*}\n'
            + ('\\tabnote{' + note + '}\n' if note else '') + '\\end{table}\n')


def panel(caption, label, columns, header, rows):
    """A compact paper panel; its caller supplies the table/subtable container."""
    return ('\\caption{' + caption + '}\n'
            + ('\\label{' + label + '}\n' if label else '')
            + r'\fontsize{9}{10.5}\selectfont' + '\n'
            + r'\renewcommand{\arraystretch}{1.08}' + '\n'
            + r'\setlength{\tabcolsep}{3pt}' + '\n'
            + r'\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}' + columns + '@{}}\n'
            + '\\toprule\n' + header + r' \\' + '\n\\midrule\n'
            + '\n'.join(row if row.startswith(('\\midrule', '\\addlinespace'))
                        else row + r' \\' for row in rows)
            + '\n\\bottomrule\n\\end{tabular*}\n')


def answer_check_ablation(report):
    """Three paired configurations; counts and percentages share one holdout."""
    e = report['evaluations']['intent_holdout_seed0']
    methods = e['methods']
    rows = []
    for key, label in [('dg_only', 'DG-only'),
                       ('answer_check_shared_eta', r'DG + Answer Check, fixed $\eta$'),
                       ('full_joint', 'DG + Answer Check, joint calibration')]:
        r = methods[key]
        rows.append(f"{label} & {r['successes']}/{r['denominator']} & {100*r['asr']:.2f} & {100*r['fpr']:.2f}")
    u, c = methods['undefended'], methods['cosine_only']
    note = (f"{e['n_calibration_benign']} benign intents calibrate thresholds; "
            f"{e['n_attack_intents']} held-out intents provide {e['n_attack']} attack "
            f"and {e['n_test_benign']} benign pairs. The split is by intent (seed 0). "
            r"All rows use $\tau=0.90$. The middle row holds the DG-only threshold "
            r"fixed; the last row refits it at the same nominal 5\% FPR budget. "
            f"Undefended ASR is {100*u['asr']:.2f}\\%; cosine-only ASR/FPR are "
            f"{100*c['asr']:.2f}\\%/{100*c['fpr']:.2f}\\%. "
            r"Success counts jointly require retrieval, acceptance and an injection-success verdict.")
    return table(r'Answer Check ablation on SC-IPI/KCA (\eFive{}).',
                 'tab:answer-check-ablation', 'lrrr',
                 r'Configuration & Successes / attacks & ASR (\%) $\downarrow$ & FPR (\%) $\downarrow$',
                 rows, note, size='9', leading='10.5')


def build(data_root: Path):
    sources = {}
    outputs = {}
    supplements = {}

    def read(path):
        path = Path(path)
        raw = path.read_bytes()
        if raw.startswith(b'version https://git-lfs.github.com/spec/v1'):
            raise ValueError(f'LFS pointer is not evidence: {path}')
        prefix, rel = ('data', path.relative_to(data_root)) if path.is_relative_to(data_root) else ('code', path.relative_to(REPO))
        sources[f'{prefix}:{rel}'] = hashlib.sha256(raw).hexdigest()
        return json.loads(raw)

    def result(rel):
        return read(RESULTS / rel)

    def put(name, text):
        outputs[f'tab/appendix_{name}.tex'] = '% Generated by experiments.paper.figures.appendix_tables.\n' + text

    ablation = result('sc_ipi_20260920/aligned_summary.json')
    put('answer_check', answer_check_ablation(ablation))

    cap = read(data_root / 'datasets/final500/sets/lmp_800.json')
    evpath = data_root / 'datasets/final500/eval/lmp_eval.jsonl'
    raw = evpath.read_bytes()
    sources['data:datasets/final500/eval/lmp_eval.jsonl'] = hashlib.sha256(raw).hexdigest()
    lengths = {}
    for line in raw.splitlines():
        row = json.loads(line)
        if row['query_role'] == 'ndss':
            lengths.setdefault(row['generator'], []).append(len(row['text'].split()))
    rows = []
    for name in ['compress_append', 'blend', 'fuse']:
        key = 'ndss_matched_' + name
        f, n = cap['per_family'][key], lengths[key]
        assert len(n) == f['selected']
        rows.append(f"{tex(name.replace('_', '-'))} & {f['available_rows']} & {f['selected']} & {f['n_intents_covered']} & {statistics.median(n):g} & {min(n)}--{max(n)}")
    assert sum(map(len, lengths.values())) == cap['n_distinct_texts'] == 800
    put('cap_statistics', table('CAP source and selected-set statistics.', 'tab:cap-statistics', 'lrrrrr',
        r'Construction & Source rows & Selected & Intents & Median words & Word range', rows,
        r'Word counts use whitespace splitting on selected entries. Length matching during construction uses characters, within $\pm10\%$ of the same-intent benign median. Intent counts overlap across constructions.'))

    b = result('v3/operating/bottleneck_e5.json')
    ab = result('v3/ablations_v3.json')['sets']
    paws_rows = [f"Cosine & {b['baselines']['cosine_paws_test']:.3f}",
                 f"Pair-embedding predictor & {b['arms']['Z (pair of embeddings)']['logistic']['paws_test']:.3f}",
                 f"Joint-encoding control & {b['arms']['X (joint text)']['logistic']['paws_test']:.3f}"]
    rows = []
    for label, key in [('DG', 'excess_count6'), ('Anchor-free coherence', 'no_anchor_split'), ('Span coefficient of variation', 'span_cv'), ('Span range', 'span_range')]:
        rows.append(f"{label} & {ab['LMP']['variants'][key]['auroc']:.3f}")
    put('representation', r'\begin{table}[!htbp]' + '\n' + r'\centering' + '\n'
        + r'\caption{Representation controls (PAWS) and DG ablations (CAP, six equal segments).}' + '\n'
        + r'\label{tab:representation}' + '\n'
        + r'\begin{subtable}[t]{0.48\linewidth}' + '\n'
        + panel('PAWS: representation', '', 'lr', r'Predictor & AUC $\uparrow$', paws_rows)
        + r'\end{subtable}\hfill' + '\n' + r'\begin{subtable}[t]{0.48\linewidth}' + '\n'
        + panel('CAP: statistic ablations', '', 'lr', r'Statistic & AUC $\uparrow$', rows)
        + '\\end{subtable}\n\\end{table}\n')

    grids = {s: result(f'v3/granularity32/g32_{s}.json') for s in ['cap', 'scp', 'kca']}
    dep = 'multi[count:4+width:2:cap16]/runs'
    rows = []
    for policy, cell in grids['cap']['grid'].items():
        per = [grids[s]['grid'][policy] for s in grids]
        cost = math.exp(statistics.mean(math.log(grids[s]['grid'][policy]['dots_per_hit']['pooled']['mean'] / grids[s]['grid'][dep]['dots_per_hit']['pooled']['mean']) for s in grids))
        unj = max(grids[s]['grid'][policy]['n_benign_unjudgeable'] / grids[s]['n_benign_total'] for s in grids)
        short = policy.replace('multi[', '').replace(']', '').replace('count:', 'N').replace('width:', 'w').replace(':cap16', '')
        rows.append(f"{tex(short)} & " + ' & '.join(f"{c['block_at_budget']:.3f}" for c in per)
                    + f" & {cost:.2f} & {cell['threshold_scoring']:.5f} & {per[2]['threshold_scoring']:.5f} & {100*unj:.1f}")
    assert len(rows) == 32
    put('segmentation', table(r'Full segmentation sweep underlying Figure~\ref{fig:tradeoff} (DG only).', 'tab:segmentation-full', 'lrrrrrrr',
        r'Scheme & CAP BR & SCP BR & KCA BR & Cost & $\eta_C$ & $\eta_N$ & Miss (\%)', rows,
        r'$N$: equal-count; $w$: word-width, capped at 16 segments; /runs: all proper contiguous windows. Without /runs, the historical span policy tests individual segments and leave-one-segment-out variants. Cost is the geometric mean of pooled variant-count ratios to 4+2 across the three sets. $\eta_C$ and $\eta_N$ are ComQA and Natural Questions benign thresholds. Miss is the largest unsegmentable benign share; shares above 1\% are excluded from the frontier. Two-segment rows explicitly relax the minimum segment count to two. Same-corpus cosine BR is 0.240/0.372/0.955 for CAP/SCP/KCA.', size='8', leading='9.3'))

    residual = result('v3/adaptive/rq6_search_v3.json')
    rows = []
    for bucket, label in [('<=2', r'$\le2$'), ('3-6','3--6'), ('7-10','7--10'), ('>10', '$>10$')]:
        c = residual['by_payload_words'][bucket]
        rows.append(f"{label} & {c['n']} & {round(c['n']*c['strict_rate'])} & {c['strict_rate']:.3f} & {c['median_excess']:.5f}")
    put('residual', table(r'Residual-length data in Figure~\ref{fig:panels} (left).', 'tab:residual-length', 'lrrrr',
        r'Added words & Candidates & Strict successes & Fraction & Median DG', rows,
        r'The 206 candidates survive the historical DG-only filter; they come from 200 targets. Fractions are candidate-level and conditioned on survival, not end-to-end target ASR.'))

    rows = []
    qqp = []
